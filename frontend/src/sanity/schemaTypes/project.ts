import { defineType, defineField } from 'sanity';

export const projectType = defineType({
  name: 'project',
  title: 'Case Study / Project',
  type: 'document',
  fields: [
    defineField({
      name: 'title',
      title: 'Title',
      type: 'string',
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'slug',
      title: 'Slug',
      type: 'slug',
      options: {
        source: 'title',
        maxLength: 96,
      },
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'client',
      title: 'Client Partner Name',
      type: 'string',
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'industry',
      title: 'Industry Category',
      type: 'string',
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'shortDescription',
      title: 'Homepage Short Description',
      type: 'string',
      description: 'Concise one-line summary shown in the homepage client selector (max 110 characters).',
      validation: (Rule) => Rule.max(110),
    }),
    defineField({
      name: 'headline',
      title: 'Case Headline',
      type: 'string',
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'overview',
      title: 'Executive Overview',
      type: 'text',
      rows: 4,
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'summary',
      title: 'Project Summary',
      type: 'text',
      rows: 3,
      description: 'Executive project summary. Falls back to shortDescription or overview opening.',
    }),
    defineField({
      name: 'challenge',
      title: 'Client Challenge & Bottleneck',
      type: 'text',
      rows: 4,
      description: 'The core bottleneck, market condition, or problem faced before ThunSpark engagement.',
    }),
    defineField({
      name: 'strategy',
      title: 'Strategic Growth Thesis',
      type: 'text',
      rows: 4,
      description: 'The strategic approach, hypothesis, and systems architecture implemented.',
    }),
    defineField({
      name: 'services',
      title: 'Services Rendered Tags',
      type: 'array',
      of: [{ type: 'string' }],
      description: 'Disciplines involved (e.g. Full-Stack Web, Paid Ads, Social Media).',
    }),
    defineField({
      name: 'deliverables',
      title: 'Delivered Capabilities',
      type: 'array',
      of: [{ type: 'string' }],
      description: 'Tangible assets and infrastructure delivered.',
    }),
    defineField({
      name: 'outcomes',
      title: 'Measured Outcomes',
      type: 'array',
      description: 'Metrics and growth results. Shown publicly ONLY when verified AND permission are true.',
      of: [
        {
          type: 'object',
          name: 'outcomeMetric',
          title: 'Outcome Metric',
          fields: [
            defineField({
              name: 'label',
              title: 'Metric Label',
              type: 'string',
              validation: (Rule) => Rule.required(),
            }),
            defineField({
              name: 'value',
              title: 'Metric Value',
              type: 'string',
              description: 'e.g. +142%, 3.8x, 48h',
            }),
            defineField({
              name: 'verified',
              title: 'Audited & Verified',
              type: 'boolean',
              description: 'Whether this metric is audited and verified from analytics/CRM.',
              initialValue: false,
              validation: (Rule) => Rule.required(),
            }),
            defineField({
              name: 'permission',
              title: 'Client Publication Clearance',
              type: 'boolean',
              description: 'Whether the client has granted explicit legal permission to publish.',
              initialValue: false,
              validation: (Rule) => Rule.required(),
            }),
          ],
        },
      ],
    }),
    defineField({
      name: 'gallery',
      title: 'Project Visual Gallery',
      type: 'array',
      of: [
        {
          type: 'object',
          name: 'galleryItem',
          title: 'Gallery Item',
          fields: [
            defineField({
              name: 'image',
              title: 'Image',
              type: 'image',
              options: { hotspot: true },
              validation: (Rule) => Rule.required(),
            }),
            defineField({
              name: 'alt',
              title: 'Alt Text',
              type: 'string',
              description: 'Required accessibility description.',
              validation: (Rule) => Rule.required(),
            }),
            defineField({
              name: 'caption',
              title: 'Optional Caption',
              type: 'string',
            }),
          ],
        },
      ],
    }),
    defineField({
      name: 'scope',
      title: 'Delivered Scope Items',
      type: 'array',
      of: [{ type: 'string' }],
    }),
    defineField({
      name: 'servicesRendered',
      title: 'Services Rendered Tags',
      type: 'array',
      of: [{ type: 'string' }],
    }),
    defineField({
      name: 'year',
      title: 'Completion Year',
      type: 'number',
      initialValue: 2024,
    }),
    defineField({
      name: 'honestyNote',
      title: 'Data Honesty Note',
      type: 'string',
      initialValue: 'Scope-first showcase. Detailed revenue metrics remain client-confidential.',
    }),
    defineField({
      name: 'featured',
      title: 'Featured On Homepage',
      type: 'boolean',
      initialValue: false,
    }),
    defineField({
      name: 'logo',
      title: 'Client Logo',
      type: 'image',
      description: 'Optional client logo (rendered on a light rounded tile when no cover image is set).',
      options: {
        hotspot: false,
      },
    }),
    defineField({
      name: 'cover',
      title: 'Cover Image',
      type: 'image',
      description: 'Featured project visual displayed in the homepage selector.',
      options: {
        hotspot: true,
      },
    }),
    defineField({
      name: 'coverImage',
      title: 'Legacy Cover Image (Deprecated)',
      type: 'image',
      hidden: true,
      options: {
        hotspot: true,
      },
    }),
  ],
});
